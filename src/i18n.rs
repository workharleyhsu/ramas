/// Table for a language.
pub fn strings(lang: Lang) -> &'static Strings {
    match lang {
        Lang::En => &EN,
        Lang::Es => &ES,
    }
}

impl Strings {
    /// Display label of a category key (custom keys show as-is).
    pub fn category<'a>(&self, key: &'a str) -> &'a str {
        self.categories
            .iter()
            .find(|(k, _)| *k == key)
            .map_or(key, |(_, label)| label)
    }
}

/// Replaces each `{key}` in `template` with its value.
pub fn fill(template: &str, vars: &[(&str, &str)]) -> String {
    let mut out = template.to_owned();
    for (k, v) in vars {
        out = out.replace(&format!("{{{k}}}"), v);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_replaces_placeholders() {
        assert_eq!(
            fill(EN.marked, &[("n", "3"), ("size", "1 GiB")]),
            "3 marked — 1 GiB to free"
        );
    }

    #[test]
    fn tables_have_same_help_length() {
        assert_eq!(EN.help_lines.len(), ES.help_lines.len());
        assert_eq!(ES.confirm_word, "borrar");
    }
}
